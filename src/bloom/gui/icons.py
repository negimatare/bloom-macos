_SCALE = 2  # draw at Retina resolution


def pixmap(name: str, colour: str, size: int = 16) -> QPixmap:
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" '
        f'stroke="{colour}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
        f"{_SVG[name]}</svg>"
    )
    image = QPixmap(size * _SCALE, size * _SCALE)
    image.fill(Qt.transparent)
    painter = QPainter(image)
    QSvgRenderer(QByteArray(svg.encode())).render(painter)
    painter.end()
    image.setDevicePixelRatio(_SCALE)
    return image


def icon(name: str, colour: str = theme.TEXT, checked_colour: str | None = None) -> QIcon:
    result = QIcon(pixmap(name, colour))
    if checked_colour:
        result.addPixmap(pixmap(name, checked_colour), QIcon.Normal, QIcon.On)
    return result
